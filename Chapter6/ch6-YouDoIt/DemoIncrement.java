public class DemoIncrement {
    public static void main(String[] args) {
        int v = 4;
        int plusPlus = ++v;
        v = 4;
        int vPlusPlus = v++;
        System.out.println("v is " + v);
        System.out.println("++v is " + plusPlus);
        System.out.println("v++ is " + vPlusPlus);
    }
}
